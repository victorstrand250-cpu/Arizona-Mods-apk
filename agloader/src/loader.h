#pragma once

#include <jni.h>

#include <string>

namespace ag::loader {

struct Screen {
  int width = 0;
  int height = 0;
};

// Состояние загрузчика — для меню и Lua API.
bool ready();          // движок найден, якоря перехвачены
Screen screen();
double frame_time();   // секунды между кадрами
long long frame_count();

JavaVM* vm();

// Размер экрана берётся из androidResize, а если игра его не вызвала —
// из вьюпорта GL при поднятии интерфейса.
void set_screen(int width, int height);

// Отправляет строку в игровой чат так же, как если бы её напечатал игрок:
// через публичный GTASA.t_OnInputEnd(), который сам перекладывает вызов
// на UI-поток. Возвращает false, если активити ещё не поймана
// (до первой отправки чего-либо из чата её объект нам недоступен).
bool send_chat(const std::string& text);
bool can_send_chat();

// Подкладывает игре касание экрана так, будто его сделал палец.
//
// Управление в игре — экранное: джойстик, кнопки. Значит, чтобы вести
// персонажа самому, не нужно знать ни одной внутренней функции движка —
// достаточно нажимать те же места, что нажимает игрок. Событие уходит
// прямиком в оригинальный androidMultiTouch, минуя наш перехват, иначе оно
// вернулось бы к нам же.
//
// action: 0 — палец опущен, 1 — поднят, 2 — двигается.
// Звать только с потока отрисовки, то есть из main() или событий скрипта.
bool inject_touch(int action, int pointer_id, int x, int y);

// Клавиатура игры — та же, что открывается под чатом, со всеми её
// раскладками и настройками. Своей рисовать не надо: у игры есть публичный
// GTASA.SetInputLayout(тип, это_чат), который сам перекладывает вызов на
// UI-поток, а напечатанное приходит в OnInputEnd — его мы и так
// перехватываем.
//
// Возвращает false, если метод или объект активити не нашлись; тогда
// остаётся нарисованная клавиатура загрузчика.
bool keyboard_available();
bool show_keyboard();
void hide_keyboard();

}  // namespace ag::loader
